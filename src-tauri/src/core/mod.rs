//! 核心层（core）—— 可单测的业务实现，不依赖 Tauri 运行时
//!
//! 分层意义：
//! - commands 只做参数校验与转发；真正逻辑放这里，便于 `cargo test` 单测
//! - 本层不引入 `tauri::` 类型（除了少量必要的数据结构），保持可移植
//!
//! 子模块规划：
//! - crypto.rs     私有空间加密：Argon2id 派生 / AES-256-GCM 分块加解密 / 密钥清零
//! - paths.rs      路径安全：作用域校验（防目录穿越）/ 规范化 / 扩展名与类型判定
//! - fs_watch.rs   文件监听：notify 封装，外部修改时通知前端重载编辑器
//! - ai_client.rs  AI 客户端：OpenAI 兼容协议 / SSE 流式解析 / 超时重试 / 取消
